-- Execute no SQL Editor do projeto Supabase antes de iniciar a agenda.
-- A agenda usa apenas o servidor Node, que acessa o banco com uma chave secreta.

create table if not exists public.clients (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  first_contact date,
  regions jsonb not null default '[]'::jsonb,
  treatment_type text not null check (treatment_type in ('Estrias', 'Cicatriz', 'Estrias e cicatrizes')),
  notes text not null default '',
  created_at timestamptz not null default now(),
  constraint clients_regions_array check (jsonb_typeof(regions) = 'array')
);

create index if not exists clients_full_name_order on public.clients (lower(full_name));

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  client_id bigint not null references public.clients(id) on delete restrict,
  date date not null,
  time time without time zone not null,
  amount_cents integer not null check (amount_cents > 0),
  installments smallint not null default 1 check (installments in (1, 2)),
  second_due_date date,
  second_amount_cents integer,
  status text not null default 'scheduled' check (status in ('scheduled', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  constraint appointments_second_payment check (
    (installments = 1 and second_due_date is null and second_amount_cents is null)
    or (installments = 2 and second_due_date is not null and second_amount_cents > 0)
  )
);

create unique index if not exists appointments_unique_active_slot
  on public.appointments (date, time)
  where status <> 'cancelled';
create index if not exists appointments_date_status on public.appointments (date, status);
create index if not exists appointments_client on public.appointments (client_id);

create table if not exists public.settings (
  key text primary key,
  value text not null default ''
);

create table if not exists public.sessions (
  token_hash text primary key,
  expires_at bigint not null
);

alter table public.clients enable row level security;
alter table public.appointments enable row level security;
alter table public.settings enable row level security;
alter table public.sessions enable row level security;

-- Intencionalmente não há políticas para anon/authenticated. O servidor valida
-- a sessão própria da agenda e acessa o banco usando a chave secreta.
